export function normalizeLocale(locale) {
  return String(locale ?? '').toLowerCase().startsWith('zh') ? 'zh-TW' : 'en'
}

export function translate(locale, key, variables = {}) {
  const value = messages[normalizeLocale(locale)]?.[key] ?? messages.en[key] ?? key
  return value.replace(/\{(\w+)\}/g, (_match, name) => String(variables[name] ?? ''))
}
