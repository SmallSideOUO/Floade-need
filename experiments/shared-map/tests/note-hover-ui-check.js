async page => {
  // Run only against a dedicated synthetic --map-profile, never a user profile.
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.reload();await page.locator('.node').first().waitFor();
  const check=(value,message)=>{if(!value)throw new Error(message)};
  const read=()=>page.evaluate(()=>window.mapStore.load());
  const initial=await read();check(initial.graph.nodes.length===10,'Use a synthetic profile');
  const original=initial.graph.nodes.find(n=>n.id==='world');
  const orb=()=>page.locator('.note-orb[data-node-id="world"]');
  const preview=page.locator('#note-preview'),copy=preview.locator('.note-preview-copy');
  const bubble=page.locator('.note-popover[data-panel-id="world"]');
  const main=page.locator('.object-panel[data-kind="node"][data-panel-id="world"]');
  const moveAway=async()=>{const box=await page.locator('#canvas').boundingBox();await page.mouse.move(box.x+box.width-15,box.y+box.height-70)};
  await page.keyboard.press('Escape');
  for(const close of await page.locator('.object-panel [data-action="close"]').all())await close.click();
  await page.locator('#visual-mode').selectOption('show');
  await orb().click();
  const note='HOVER_PREVIEW\n<img src=x onerror=alert(1)>\n'+Array.from({length:50},(_,i)=>'第 '+(i+1)+' 行補充文字').join('\n');
  await bubble.locator('textarea').fill(note);await page.waitForTimeout(220);await page.keyboard.press('Escape');await moveAway();
  const before=await read();
  await orb().hover();await preview.waitFor({state:'visible'});
  check(await copy.textContent()===note,'Preview lost note text or line breaks');
  check(await copy.locator('img').count()===0,'Preview interpreted note as HTML');
  check(await bubble.count()===0,'Hover opened the editor');
  const after=await read();check(after.revision===before.revision&&JSON.stringify(after.graph)===JSON.stringify(before.graph),'Hover changed or saved the graph');
  const canvasBox=await page.locator('#canvas').boundingBox(),previewBox=await preview.boundingBox();
  check(previewBox.x>=canvasBox.x&&previewBox.y>=canvasBox.y&&previewBox.x+previewBox.width<=canvasBox.x+canvasBox.width&&previewBox.y+previewBox.height<=canvasBox.y+canvasBox.height,'Preview exceeds canvas bounds');
  await preview.hover();await page.waitForTimeout(250);check(await preview.isVisible(),'Preview disappeared when entering it');
  const scale=await page.locator('#scale').textContent();await page.mouse.wheel(0,250);
  await page.waitForFunction(()=>document.querySelector('#note-preview').scrollTop>0,{},{timeout:5000});
  check(await preview.evaluate(el=>el.scrollTop)>0,'Long note preview does not scroll');
  check(await page.locator('#scale').textContent()===scale,'Preview scroll zoomed the canvas');
  await moveAway();await preview.waitFor({state:'hidden'});check(await copy.textContent()==='','Hidden preview retained text in DOM');
  await orb().hover();await moveAway();await page.waitForTimeout(400);check(!await preview.isVisible(),'Preview appeared after leaving before the delay');
  await orb().hover();await preview.waitFor({state:'visible'});await orb().click();
  check(!await preview.isVisible()&&await bubble.isVisible(),'Click did not replace preview with editor');
  await page.keyboard.press('Escape');await moveAway();await orb().hover();await preview.waitFor({state:'visible'});
  await orb().click({button:'right'});check(!await preview.isVisible(),'Context menu left preview visible');
  await page.locator('[data-menu="clear-note"]').click();await moveAway();await orb().hover();await page.waitForTimeout(400);
  check(!await preview.isVisible(),'Empty note has a preview');
  await orb().click();await bubble.locator('textarea').fill(note);await page.waitForTimeout(220);await page.keyboard.press('Escape');await moveAway();
  await orb().hover();await preview.waitFor({state:'visible'});await page.locator('#visual-mode').selectOption('mask');
  check(!await preview.isVisible()&&await copy.textContent()==='','Changing privacy left preview text visible');
  await orb().hover();await page.waitForTimeout(400);check(!await preview.isVisible(),'Masked note leaked via hover');
  await page.locator('#visual-mode').selectOption('show');await page.locator('.node[data-id="world"]').click();
  await main.locator('[data-field="aiVisibility"]').selectOption('text');await main.locator('[data-action="close"]').click();await moveAway();
  await orb().hover();await preview.waitFor({state:'visible'});check(await copy.textContent()===note,'AI privacy incorrectly changed visual preview');
  await page.locator('.node[data-id="world"]').click();await main.locator('[data-field="visualVisibility"]').selectOption('object');
  await page.locator('#visual-mode').selectOption('selective');check(await orb().count()===0&&!await preview.isVisible(),'Hidden node left preview controls');
  await page.locator('#visual-mode').selectOption('show');await page.locator('.node[data-id="world"]').click();
  await main.locator('[data-field="aiVisibility"]').selectOption(original.aiVisibility||'full');
  await main.locator('[data-field="visualVisibility"]').selectOption(original.visualVisibility||'full');
  await main.locator('[data-action="close"]').click();await orb().click();await bubble.locator('textarea').fill(original.note||'');
  await page.waitForTimeout(220);await page.keyboard.press('Escape');await moveAway();
  check(errors.length===0,'Renderer errors: '+errors.join('; '));
  return {passed:true,checks:['hover text and line breaks','HTML rendered as text','no graph writes','viewport bounds','scroll without canvas zoom','leave and delay cancellation','click edit','right-click clear','empty notes','visual privacy','AI privacy independent','hidden nodes']};
}
